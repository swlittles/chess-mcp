#!/usr/bin/env node
// Rebuilds src/chess/pieces.ts from the Cburnett chess piece SVGs on Wikimedia Commons
// (File:Chess_klt45.svg and friends). Cburnett licenses them under GFDL, BSD or GPL; this project
// uses them under BSD (see THIRD_PARTY_NOTICES.md).
//
//   node scripts/build-pieces.mjs <folder with Chess_{k,q,r,b,n,p}{l,d}t45.svg>
//
// Only plain shapes are kept: anything other than <g>, <path> and <circle> is refused.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: node scripts/build-pieces.mjs <folder>");
  process.exit(2);
}

const pieces = {};
for (const [color, suffix] of [["w", "l"], ["b", "d"]]) {
  for (const type of ["k", "q", "r", "b", "n", "p"]) {
    const file = `Chess_${type}${suffix}t45.svg`;
    const svg = readFileSync(join(dir, file), "utf8");
    const inner = svg
      .replace(/<\?xml[^>]*\?>/, "")
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>\s*$/, "")
      .replace(/\s+/g, " ")
      .replace(/>\s+</g, "><")
      .trim();
    const tags = [...inner.matchAll(/<\/?([a-zA-Z:]+)/g)].map((m) => m[1]);
    const unexpected = tags.filter((t) => !["g", "path", "circle"].includes(t));
    if (unexpected.length || /href|on[a-z]+=|url\(/i.test(inner)) throw new Error(`${file}: unexpected content (${unexpected.join(", ")})`);
    pieces[`${color}${type.toUpperCase()}`] = inner;
  }
}

const body = Object.entries(pieces)
  .map(([key, svg]) => `  ${key}: ${JSON.stringify(svg)},`)
  .join("\n");
writeFileSync(
  "src/chess/pieces.ts",
  `// Generated by scripts/build-pieces.mjs from the Cburnett chess pieces on Wikimedia Commons.
// Copyright Colin M.L. Burnett, used under the BSD license (see THIRD_PARTY_NOTICES.md).
// Each piece is drawn in a 45x45 box.

export const PIECES: Record<string, string> = {
${body}
};
`,
);
console.log(`Wrote ${Object.keys(pieces).length} pieces to src/chess/pieces.ts.`);
